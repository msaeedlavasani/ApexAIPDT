import { createOrchestratorCore } from './orchestrator-core.mjs';
import { createMemoryRuntime } from './memory-runtime.mjs';
import { createWorkflowRuntime } from './workflow-runtime.mjs';
import { createQualityGateRuntime } from './qualitygate-runtime.mjs';
import { createApprovalUIRuntime } from './approval-ui-runtime.mjs';
import { GooseAdapter } from './goose-adapter.mjs';
import { DOMAIN, AUTHORITY_MODE } from '../contract/provider-contract.mjs';
import { join, resolve } from 'path';
const assert = (c,n) => { if(c){console.log('  [PASS] '+n); return true;}else{console.log('  [FAIL] '+n); return false;} };
let p=0,f=0; const a=(c,n)=>{if(assert(c,n))p++;else f++;};
console.log('\n=== DPT-FOUNDATION-030: V1 End-to-End Integration ===');
const REPO = resolve(process.cwd());
const mem = createMemoryRuntime({ storePath: join(REPO, 'providers/goose/.dpt-e2e-memory.json') });
const wf = createWorkflowRuntime();
const qg = createQualityGateRuntime({ gates: [
  { id: 'e2e-test', applies_to: ['*'], evaluate: async (r) => ({ passed: r.tests >= 18, reason: 'e2e tests' }) }
]});
const orch = createOrchestratorCore({ memory: mem, workflow: wf, qualityGate: qg });
const goose = new GooseAdapter({ root_dir: REPO });
const ui = createApprovalUIRuntime();
const envelope = { envelope_id: 'E2E-1', permissions: [{ domain: DOMAIN.FILESYSTEM, action: ['read','write'], resource: join(REPO,'docs/**'), authority_mode: AUTHORITY_MODE.AUTO_ALLOW }], status: 'ACTIVE' };
goose.registerEnvelope('E2E-1', 'WO-E2E', envelope);
const session = await goose.createSession({ task_id: 'E2E-1', work_order_id: 'WO-E2E' });
const r1 = await goose.executeTool(session, { tool_name: 'write', params: { path: join(REPO, 'docs/e2e_test_v1.json'), content: JSON.stringify({e2e:true,ts:Date.now()}) } });
a(r1.executed === true, 'Goose adapter wrote through gateway');
a(r1.status === 'EXECUTED', 'Status EXECUTED');
const readiness = await orch.computeReadiness({ task_id: 'T1', dependencies: [] });
a(readiness.ready === true, 'Orchestrator computed readiness');
const auth = await orch.materializeAuthority({ task_id:'T1', resource_claims:[] }, envelope);
a(auth.authorized === true, 'Authority materialized');
wf.transition('READY'); wf.transition('RUNNING');
a(wf.getState() === 'RUNNING', 'Workflow state machine advanced');
const gateResult = await qg.execute({ task_class: 'implementation' }, { tests: 18 });
a(gateResult.verified === true, 'Quality gate passed');
const decision = await ui.presentDecision({ hg_id: null, task_id: 'T1', question: 'Continue?', choice_a: 'approve', choice_b: 'reject' });
a(decision.response?.action === 'approve', 'UI presented decision');
const noHg = ui.evaluateHgMatch('T1', 'write spec');
a(noHg.match === null, 'Spec writing is not a Human Gate');
console.log('\nRESULTS: '+p+'/'+(p+f)+' PASS'); if(f>0){console.log('FAILURES'); process.exit(1);} else console.log('ALL PASS');
